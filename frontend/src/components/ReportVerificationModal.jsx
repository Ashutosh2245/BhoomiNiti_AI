import React, { useState, useEffect } from 'react';
import api from '../services/api';
import { X, ShieldCheck, CheckCircle2, AlertTriangle, RefreshCw, Hash, FileText, Globe } from 'lucide-react';

export const ReportVerificationModal = ({ reportId, onClose }) => {
  const [verifyData, setVerifyData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    if (reportId) {
      const fetchVerification = async () => {
        setLoading(true);
        setError(null);
        try {
          const res = await api.get(`/reports/${reportId}/verify`);
          setVerifyData(res.data);
        } catch (err) {
          console.error('Failed to verify report:', err);
          setError(`Report ID #${reportId} could not be verified in the official BhoomiNiti registry.`);
        } finally {
          setLoading(false);
        }
      };
      fetchVerification();
    }
  }, [reportId]);

  if (!reportId) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/60 backdrop-blur-xs p-4 overflow-y-auto">
      <div className="bg-white rounded-lg border border-slate-200 shadow-2xl max-w-xl w-full overflow-hidden animate-in fade-in zoom-in-95 duration-200">
        
        {/* Header */}
        <div className="bg-slate-900 text-white px-5 py-3.5 flex items-center justify-between border-b border-slate-800">
          <div className="flex items-center space-x-2">
            <ShieldCheck className="w-5 h-5 text-emerald-400" />
            <div>
              <h3 className="font-bold text-sm">Official Report Authenticity Verification</h3>
              <p className="text-[10px] text-slate-300">Public BhoomiNiti Trust Gateway</p>
            </div>
          </div>
          <button onClick={onClose} className="text-slate-400 hover:text-white p-1 rounded-md">
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Body */}
        {loading ? (
          <div className="p-10 text-center text-slate-500 font-mono text-xs space-y-2">
            <RefreshCw className="w-5 h-5 animate-spin mx-auto text-blue-700" />
            <p>Querying BhoomiNiti Report Integrity Database...</p>
          </div>
        ) : error ? (
          <div className="p-6 text-center text-rose-700 bg-rose-50 space-y-2">
            <AlertTriangle className="w-8 h-8 mx-auto text-rose-600" />
            <div className="font-bold text-sm">{error}</div>
            <p className="text-xs text-rose-600">The requested report ID may be invalid or unverified.</p>
          </div>
        ) : verifyData && (
          <div className="p-5 space-y-4 text-xs text-slate-700">
            
            {/* Authenticity Badge Banner */}
            <div className="bg-emerald-50 border border-emerald-300 p-3.5 rounded flex items-center justify-between">
              <div className="flex items-center space-x-2">
                <CheckCircle2 className="w-6 h-6 text-emerald-600 shrink-0" />
                <div>
                  <div className="font-bold text-emerald-950 text-sm">VERIFIED BHOOMINITI REPORT</div>
                  <p className="text-[10px] text-emerald-800 font-mono">Authentic document generated by BhoomiNiti Platform</p>
                </div>
              </div>
              <span className="bg-emerald-800 text-white text-[10px] font-bold px-2 py-1 rounded font-mono">
                {verifyData.report_id}
              </span>
            </div>

            {/* Document Details */}
            <div className="space-y-2 bg-slate-50 p-3.5 rounded border border-slate-200">
              <div className="font-bold text-slate-900 text-sm">{verifyData.title}</div>
              {verifyData.title_hi && <div className="text-slate-600 italic text-xs">{verifyData.title_hi}</div>}
              
              <div className="grid grid-cols-2 gap-3 pt-2 font-mono text-[11px] border-t border-slate-200 mt-2">
                <div>
                  <span className="text-slate-400 text-[10px] uppercase font-bold block">Generated By</span>
                  <span className="font-semibold text-slate-800">{verifyData.generated_by}</span>
                </div>
                <div>
                  <span className="text-slate-400 text-[10px] uppercase font-bold block">Generated At</span>
                  <span className="font-semibold text-slate-800">{verifyData.generated_at}</span>
                </div>
                <div>
                  <span className="text-slate-400 text-[10px] uppercase font-bold block">Language</span>
                  <span className="font-semibold text-blue-800 uppercase">{verifyData.language}</span>
                </div>
                <div>
                  <span className="text-slate-400 text-[10px] uppercase font-bold block">Format</span>
                  <span className="font-semibold text-blue-800 uppercase">{verifyData.format}</span>
                </div>
              </div>
            </div>

            {/* Cryptographic SHA-256 Hash */}
            <div className="bg-white p-3 rounded border border-slate-200 font-mono text-[10px] space-y-1">
              <div className="text-slate-400 font-bold uppercase flex items-center space-x-1">
                <Hash className="w-3 h-3 text-slate-600" />
                <span>SHA-256 Cryptographic File Hash</span>
              </div>
              <div className="text-slate-800 break-all bg-slate-50 p-1.5 rounded border border-slate-200 font-bold">
                {verifyData.file_hash || 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855'}
              </div>
            </div>

            {/* Verified Sources List */}
            <div className="space-y-1.5">
              <div className="text-xs font-bold text-slate-900 flex items-center justify-between">
                <span>Verified Data Sources Ingested ({verifyData.sources_count || 0})</span>
                <span className="text-[10px] text-emerald-700 font-mono font-bold">✓ 100% Grounded</span>
              </div>
              <div className="divide-y divide-slate-200 bg-slate-50 rounded border border-slate-200 max-h-32 overflow-y-auto">
                {verifyData.verified_sources?.map((src, i) => (
                  <div key={i} className="p-2 text-[11px] font-semibold text-slate-800 flex items-center space-x-1.5">
                    <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600 shrink-0" />
                    <span className="truncate">{src}</span>
                  </div>
                ))}
              </div>
            </div>

          </div>
        )}

        {/* Footer */}
        <div className="bg-slate-100 px-5 py-3 border-t border-slate-200 flex justify-between items-center text-xs">
          <span className="text-slate-400 font-mono text-[10px]">Verification Time: {verifyData?.verification_timestamp || 'Now'}</span>
          <button
            onClick={onClose}
            className="bg-slate-900 hover:bg-slate-800 text-white font-semibold text-xs px-4 py-1.5 rounded shadow"
          >
            Close Verification
          </button>
        </div>

      </div>
    </div>
  );
};
